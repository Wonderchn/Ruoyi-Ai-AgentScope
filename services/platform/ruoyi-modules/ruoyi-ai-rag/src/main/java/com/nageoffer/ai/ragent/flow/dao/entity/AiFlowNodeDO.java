package com.nageoffer.ai.ragent.flow.dao.entity;

import com.baomidou.mybatisplus.annotation.FieldFill;
import com.baomidou.mybatisplus.annotation.IdType;
import com.baomidou.mybatisplus.annotation.TableField;
import com.baomidou.mybatisplus.annotation.TableId;
import com.baomidou.mybatisplus.annotation.TableName;
import com.nageoffer.ai.ragent.framework.database.JsonbTypeHandler;
import lombok.Data;

import java.util.Date;

/**
 * 可视化工作流节点（AIFlow 图）。
 *
 * <p>表 {@code platform.ai_flow_node} 由<b>冻结迁移 V9</b> 建立
 * （{@code V9__legacy_ai_domain_ddl.sql:490-524}），本卡<b>不新增表迁移、不改冻结 DDL</b>。
 * 列类型逐列取自该 DDL：{@code id bigint identity} / {@code uuid varchar(32)} /
 * {@code workflow_id bigint} / {@code workflow_component_id bigint} / {@code user_id bigint} /
 * {@code title varchar(100)} / {@code remark varchar(500)} /
 * {@code input_config jsonb NOT NULL} / {@code node_config jsonb} /
 * {@code position_x|position_y double precision} / {@code is_deleted smallint} /
 * {@code tenant_id varchar(64)}。
 *
 * <p>{@code input_config} 是 DDL 里 <b>NOT NULL 且无默认值</b>的列：服务层创建时必须兜底
 * （{@code "{}"}），否则插入直接失败。两个 jsonb 列按 {@code JsonbTypeHandler} 以不透明
 * JSON 字符串搬运（与 {@code IngestionPipelineNodeDO} 同形），结构化校验留给后续切片。
 *
 * <p>审计列用 {@link Date} + {@code FieldFill}（与 {@code AiFlowWorkflowDO} 同口径：
 * {@code InjectionMetaObjectHandler} 的 strict 填充按字段类型逐字匹配）。
 */
@Data
@TableName("ai_flow_node")
public class AiFlowNodeDO {

    /** 主键；DDL 为 bigint GENERATED BY DEFAULT AS IDENTITY。 */
    @TableId(type = IdType.ASSIGN_ID)
    private Long id;

    /** 节点对外标识（32 位）。 */
    private String uuid;

    /** 所属工作流<b>内部</b> id（ai_flow_workflow.id）。 */
    private Long workflowId;

    /** 引用的组件内部 id（ai_flow_component.id；无引用为 0）。 */
    private Long workflowComponentId;

    /** 创建人（bigint）。 */
    private Long userId;

    /** 节点标题。 */
    private String title;

    /** 节点备注。 */
    private String remark;

    /** 输入参数模板（jsonb NOT NULL，服务层兜底 "{}"）。 */
    @TableField(typeHandler = JsonbTypeHandler.class)
    private String inputConfig;

    /** 节点执行配置（jsonb 可空）。 */
    @TableField(typeHandler = JsonbTypeHandler.class)
    private String nodeConfig;

    /** 画布 x 坐标。 */
    private Double positionX;

    /** 画布 y 坐标。 */
    private Double positionY;

    /** 逻辑删除：0 未删 1 已删。 */
    private Integer isDeleted;

    /** 租户编号。 */
    private String tenantId;

    /** 创建时间（INSERT 填充）。 */
    @TableField(fill = FieldFill.INSERT)
    private Date createTime;

    /** 更新时间（UPDATE 填充）。 */
    @TableField(fill = FieldFill.INSERT_UPDATE)
    private Date updateTime;
}
