import com.baomidou.mybatisplus.annotation.TableId;
import com.baomidou.mybatisplus.annotation.TableName;
import lombok.Data;

import java.util.Date;

/**
 * 可视化工作流边（AIFlow 图）。
 *
 * <p>表 {@code platform.ai_flow_edge} 由<b>冻结迁移 V9</b> 建立
 * （{@code V9__legacy_ai_domain_ddl.sql:463-487}），本卡<b>不新增表迁移、不改冻结 DDL</b>。
 * 列类型逐列取自该 DDL：{@code id bigint identity} / {@code uuid varchar(32)} /
 * {@code workflow_id bigint} / {@code source_node_uuid varchar(32)} /
 * {@code source_handle varchar(32)} / {@code target_node_uuid varchar(32)} /
 * {@code is_deleted smallint} / {@code tenant_id varchar(64)}。
 *
 * <p>边<b>没有 user_id 列</b>：属主边界经 {@code workflow_id} 解析到工作流后判定
 * （服务层谓词），边的自身作用域只剩 tenant。
 */
@Data
@TableName("ai_flow_edge")
public class AiFlowEdgeDO {

    /** 主键；DDL 为 bigint GENERATED BY DEFAULT AS IDENTITY。 */
    @TableId(type = IdType.ASSIGN_ID)
    private Long id;

    /** 边对外标识（32 位）。 */
    private String uuid;

    /** 所属工作流<b>内部</b> id（ai_flow_workflow.id）。 */
    private Long workflowId;

    /** 起始节点 uuid。 */
    private String sourceNodeUuid;

    /** 起始锚点标识（可空串）。 */
    private String sourceHandle;

    /** 目标节点 uuid。 */
    private String targetNodeUuid;

    /** 逻辑删除：0 未删 1 已删。 */
    private Integer isDeleted;

    /** 租户编号。 */
    private String tenantId;

    /** 创建时间（INSERT 填充）。 */
    @TableField(fill = FieldFill.INSERT)
    private Date createTime;

    /** 更新时间（UPDATE 填充）。 */
    @TableField(fill = FieldFill.INSERT_UPDATE)
    private Date updateTime;
}
