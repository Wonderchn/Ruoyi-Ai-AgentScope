-- ---------------------------------------------------------------------------
-- V22 (T1 / W3-1) — ai_execution_permit 错乱时间戳行修复（WP-027 前置）。
--
-- 决定性事实（前波实测，G-55b⑵ + 46-permits/51-acl-barrier 证据）：
--   修复前的 DefaultRevocationGuard.acquire 用两个时钟写同一行 permit：
--     acquired_at = 数据库 now()（V7 列默认），
--     expires_at  = Java Instant.now()+300s。
--   两者时区/口径不一致时产生"错乱行"：实测 `38d22513-…` 的
--   expires_at=07:21+08 而真实时钟约 15:0x+08 —— expires_at 比正确值早约 8 小时
--   （量级恰为 UTC 偏移），且 status 仍 ACTIVE。
--   后果：这类行一旦成为 drain 的"阻塞者"，"租约到期自愈"永远等不到
--   （expires_at 在过去 = 永远"已过期"，但 drain/屏障侧在修复前根本不认
--   expires_at）⇒ 屏障永久 PENDING 的帮凶。本迁移把**已存在的**错乱行修好，
--   是 (1) drain 认 expires_at 真正生效的前置；(4) 单时钟源只保证今后不再产生。
--
-- 修复谓词（窄 WHERE，刻意只用行内相对比较，不碰当前时钟）：
--   合法租约 = expires_at 在 acquired_at 之后 0..1 小时内
--   （现仓全部生产写入方：AI 侧 300s `DefaultRevocationGuard:147-152`、
--     平台侧 300s `RuoYiPlatformIdentitySource:116-117`；1 小时阈值留 12 倍裕度）。
--   异常两类（都只修 status='ACTIVE' 的行）：
--     A. expires_at < acquired_at - 60s        —— "过期于过去"（两时钟错位）
--     B. expires_at > acquired_at + 3600s      —— "远期租约"（无任何写入方会产生）
--   两个修复都把 expires_at 重置为 acquired_at + 300s（标准租约）：
--   修复只会把租约改**短**，绝不延长任何阻断窗（保守方向 = fail-closed）。
--
-- 清单纪律（T0 卡面要求）：异常必须出清单 —— 每条被修的行先落
--   platform.ai_wp027_timestamp_anomaly（append-only 台账：原 acquired_at /
--   原 expires_at / 修复后值 / 异常类别），再修复；修复后剩余异常数必须为 0，
--   否则整个迁移失败（Flyway 单迁移单事务 ⇒ 不会半修复）。
-- 幂等：第二遍执行时异常集合为空 ⇒ 修复 0 行、台账唯一键防重 ⇒ 结果不变。
-- 前后增量口径：报告的是"异常行数 前值→后值"，不是 permit 总数（T8 H-19 教训）。
-- 不碰：冻结 V7-V11 的 DDL（本迁移零 DDL 变更、零列变更）；sys_ai_execution_permit
--   （平台侧写入方单时钟 now()+5min，无错乱来源；其 drain 口径问题另行登记）。
-- ---------------------------------------------------------------------------


-- ===========================================================================
-- 1. 异常台账（只追加；清单的持久形态，供审计与幂等）
-- ===========================================================================

CREATE TABLE IF NOT EXISTS platform.ai_wp027_timestamp_anomaly (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name           varchar(64)  NOT NULL,
    column_name          varchar(64)  NOT NULL,
    row_key              text         NOT NULL,
    original_acquired_at timestamptz  NOT NULL,
    original_expires_at  timestamptz  NOT NULL,
    repaired_expires_at  timestamptz  NOT NULL,
    anomaly_kind         varchar(32)  NOT NULL,
    migration_version    varchar(16)  NOT NULL DEFAULT 'V22',
    recorded_at          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_wp027_timestamp_anomaly
        UNIQUE (table_name, column_name, row_key, original_expires_at, anomaly_kind),
    CONSTRAINT ck_wp027_timestamp_anomaly_kind
        CHECK (anomaly_kind IN ('expires_before_acquired', 'expires_far_future'))
);
COMMENT ON TABLE platform.ai_wp027_timestamp_anomaly IS
    'V22 错乱时间戳行修复台账（只追加）：每条被修的 ai_execution_permit 行修复前原值；幂等重跑不新增';

CREATE OR REPLACE FUNCTION platform.ai_wp027_timestamp_anomaly_append_only()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'ai_wp027_timestamp_anomaly is append-only: DELETE rejected (id=%)', OLD.id;
    END IF;
    RAISE EXCEPTION 'ai_wp027_timestamp_anomaly is append-only: UPDATE rejected (id=%)', OLD.id;
END;
$$;

DROP TRIGGER IF EXISTS trg_wp027_timestamp_anomaly_append_only ON platform.ai_wp027_timestamp_anomaly;
CREATE TRIGGER trg_wp027_timestamp_anomaly_append_only
    BEFORE UPDATE OR DELETE ON platform.ai_wp027_timestamp_anomaly
    FOR EACH ROW EXECUTE FUNCTION platform.ai_wp027_timestamp_anomaly_append_only();


-- ===========================================================================
-- 2. 修复本体（窄 WHERE + 先落清单 + 前后增量 + 修复后必须归零）
-- ===========================================================================

DO $wp027_v22$
DECLARE
    v_leading_before  bigint := 0;
    v_lagging_before  bigint := 0;
    v_leading_fixed   bigint := 0;
    v_lagging_fixed   bigint := 0;
    v_leading_after   bigint := 0;
    v_lagging_after   bigint := 0;
    v_anomaly_before  bigint := 0;
    v_anomaly_after   bigint := 0;
    v_detail          text;
BEGIN
    -- 适用性锚点（判据反恒真第 2 形态：让"适用性本身"成为被断言对象）。
    -- 本迁移就是为修这张表而存在：表缺席不是"无事可做"，是链路形态错了。
    IF to_regclass('platform.ai_execution_permit') IS NULL THEN
        RAISE EXCEPTION 'V22: platform.ai_execution_permit is missing; the unified chain must be applied first'
            USING HINT = 'This migration owns the timestamp anomaly repair and must not skip it silently.';
    END IF;

    -- 前值（两类异常分开计数，报告口径 = 前值→后值增量）
    SELECT count(*) INTO v_leading_before FROM platform.ai_execution_permit
     WHERE status = 'ACTIVE'
       AND expires_at < acquired_at - interval '60 seconds';
    SELECT count(*) INTO v_lagging_before FROM platform.ai_execution_permit
     WHERE status = 'ACTIVE'
       AND expires_at > acquired_at + interval '3600 seconds';
    v_anomaly_before := v_leading_before + v_lagging_before;

    IF v_anomaly_before > 0 THEN
        -- 清单先行：每条将被修的行先落台账（原值齐全），UNIQUE 键保证幂等重跑不重复
        INSERT INTO platform.ai_wp027_timestamp_anomaly
            (table_name, column_name, row_key,
             original_acquired_at, original_expires_at, repaired_expires_at, anomaly_kind)
        SELECT 'ai_execution_permit', 'expires_at', permit_id,
               acquired_at, expires_at, acquired_at + interval '300 seconds', 'expires_before_acquired'
          FROM platform.ai_execution_permit
         WHERE status = 'ACTIVE' AND expires_at < acquired_at - interval '60 seconds'
        ON CONFLICT (table_name, column_name, row_key, original_expires_at, anomaly_kind) DO NOTHING;

        INSERT INTO platform.ai_wp027_timestamp_anomaly
            (table_name, column_name, row_key,
             original_acquired_at, original_expires_at, repaired_expires_at, anomaly_kind)
        SELECT 'ai_execution_permit', 'expires_at', permit_id,
               acquired_at, expires_at, acquired_at + interval '300 seconds', 'expires_far_future'
          FROM platform.ai_execution_permit
         WHERE status = 'ACTIVE' AND expires_at > acquired_at + interval '3600 seconds'
        ON CONFLICT (table_name, column_name, row_key, original_expires_at, anomaly_kind) DO NOTHING;
    END IF;

    IF v_leading_before > 0 THEN
        UPDATE platform.ai_execution_permit
           SET expires_at = acquired_at + interval '300 seconds'
         WHERE status = 'ACTIVE' AND expires_at < acquired_at - interval '60 seconds';
        GET DIAGNOSTICS v_leading_fixed = ROW_COUNT;
    END IF;

    IF v_lagging_before > 0 THEN
        UPDATE platform.ai_execution_permit
           SET expires_at = acquired_at + interval '300 seconds'
         WHERE status = 'ACTIVE' AND expires_at > acquired_at + interval '3600 seconds';
        GET DIAGNOSTICS v_lagging_fixed = ROW_COUNT;
    END IF;

    -- 后值：两类都必须归零；任何剩余异常让整个迁移失败（清单已在台账+NOTICE 里）
    SELECT count(*) INTO v_leading_after FROM platform.ai_execution_permit
     WHERE status = 'ACTIVE' AND expires_at < acquired_at - interval '60 seconds';
    SELECT count(*) INTO v_lagging_after FROM platform.ai_execution_permit
     WHERE status = 'ACTIVE' AND expires_at > acquired_at + interval '3600 seconds';
    v_anomaly_after := v_leading_after + v_lagging_after;

    SELECT string_agg(row_key || ' [' || anomaly_kind || '] ' ||
                      to_char(original_acquired_at, 'YYYY-MM-DD HH24:MI:SSOF') || ' -> ' ||
                      to_char(original_expires_at, 'YYYY-MM-DD HH24:MI:SSOF'), E'\n  ')
      INTO v_detail
      FROM platform.ai_wp027_timestamp_anomaly
     WHERE migration_version = 'V22' AND table_name = 'ai_execution_permit';

    RAISE NOTICE 'V22 anomaly repair: leading %->% (fixed %), lagging %->% (fixed %)',
        v_leading_before, v_leading_after, v_leading_fixed,
        v_lagging_before, v_lagging_after, v_lagging_fixed;
    IF v_detail IS NOT NULL THEN
        RAISE NOTICE 'V22 repaired rows (see ai_wp027_timestamp_anomaly for full values):%  %',
            chr(10), v_detail;
    END IF;

    IF v_anomaly_after <> 0 THEN
        RAISE EXCEPTION 'V22: % anomalous timestamp row(s) remain after repair (leading=%, lagging=%); refusing to complete',
            v_anomaly_after, v_leading_after, v_lagging_after;
    END IF;
    IF v_leading_fixed <> v_leading_before OR v_lagging_fixed <> v_lagging_before THEN
        RAISE EXCEPTION 'V22: repaired count mismatch (leading %/%, lagging %/%); refusing to complete',
            v_leading_fixed, v_leading_before, v_lagging_fixed, v_lagging_before;
    END IF;
END
$wp027_v22$;


-- ===========================================================================
-- 3. 收敛断言（不静默跳过；与 V20 的断言风格一致）
-- ===========================================================================

DO $wp027_v22_assert$
DECLARE
    missing text := '';
    v_still bigint;
BEGIN
    IF to_regclass('platform.ai_wp027_timestamp_anomaly') IS NULL THEN
        missing := missing || ', ledger table ai_wp027_timestamp_anomaly';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgname = 'trg_wp027_timestamp_anomaly_append_only' AND NOT tgisinternal
    ) THEN
        missing := missing || ', trigger trg_wp027_timestamp_anomaly_append_only';
    END IF;

    -- 锚点断言（防"空集合恒真"，可证伪）：台账里记录过的每一条异常原值，
    -- 都不得仍以 (ACTIVE, 同 acquired 语义) 的形态留在 permit 行上。
    -- 若修复逻辑失效（清单落了、修复没生效），这条立即失败；健康库 0 行也成立。
    SELECT count(*) INTO v_still FROM platform.ai_execution_permit p
     WHERE p.status = 'ACTIVE'
       AND EXISTS (
           SELECT 1 FROM platform.ai_wp027_timestamp_anomaly a
            WHERE a.table_name = 'ai_execution_permit'
              AND a.column_name = 'expires_at'
              AND a.row_key = p.permit_id
              AND a.original_expires_at = p.expires_at
              AND (p.expires_at < p.acquired_at - interval '60 seconds'
                   OR p.expires_at > p.acquired_at + interval '3600 seconds'));
    IF v_still > 0 THEN
        missing := missing || ', ' || v_still || ' ledgered anomaly row(s) still carry their original expires_at';
    END IF;

    IF missing <> '' THEN
        RAISE EXCEPTION 'V22 incomplete: %', substr(missing, 3);
    END IF;
END
$wp027_v22_assert$;
